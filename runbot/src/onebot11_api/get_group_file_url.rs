//! Wraps the OneBot action `get_group_file_url`.
//!
//! The method sends a query by group number and file ID, waits for the response
//! with the matching echo, checks `retcode`, and deserializes `data` into a
//! [`GroupFileUrl`].

use crate::error::Result;
use crate::prelude::BotContext;
use serde_derive::{Deserialize, Serialize};
use tokio::time::Duration;

/// Download URL of a group file.
///
/// `url` is required: a missing field or an explicit `null` causes deserialization
/// to fail with [`crate::error::Error::JsonError`].
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct GroupFileUrl {
    /// Download URL generated by the upstream; whether it expires or requires
    /// additional credentials is defined by the upstream, and this library
    /// returns it unchanged.
    pub url: String,
}

impl BotContext {
    /// Requests the download URL of the specified group file and waits up to
    /// 10 seconds for the response.
    ///
    /// This method uses a fixed 10-second response wait and currently has no
    /// `_with_timeout` variant. The wait covers only the response phase after
    /// the request has been written to the connection; it does not include JSON
    /// serialization, internal lock acquisition, or the WebSocket write.
    ///
    /// # Arguments
    ///
    /// - `group_id`: number of the group that owns the file.
    /// - `file_id`: group file ID, returned by a group file listing API.
    ///
    /// # Errors
    ///
    /// The wait follows the semantics of [`crate::bot_context::EchoAsyncResponse::data`]: returns
    /// [`crate::error::Error::StateError`] when the current connection is
    /// unavailable (not connected, disconnected, or closed) or the response
    /// channel closes early; [`crate::error::Error::WebSocketError`] when the
    /// WebSocket write fails; [`crate::error::Error::TimeoutError`] when no
    /// response arrives within 10 seconds; and
    /// [`crate::error::Error::StateError`] when the upstream `retcode` is
    /// non-zero, with the error text taken from the response `message`. In
    /// addition, returns [`crate::error::Error::JsonError`] when `data` cannot
    /// be deserialized into [`GroupFileUrl`].
    ///
    /// # Cancellation
    ///
    /// Dropping the pending future stops the local wait and removes the matching
    /// echo registration; the request has already been written to the
    /// connection, so cancellation does not withdraw it from the upstream.
    pub async fn get_group_file_url(&self, group_id: i64, file_id: &str) -> Result<GroupFileUrl> {
        let response = self
            .websocket_send(
                "get_group_file_url",
                serde_json::json!({
                    "group_id": group_id,
                    "file_id": file_id,
                }),
            )
            .await?;
        let response = response.data(Duration::from_secs(10)).await?;
        let group_member_info: GroupFileUrl = serde_json::from_value(response)?;
        Ok(group_member_info)
    }
}
