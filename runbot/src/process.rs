//! Processor traits and the unified dispatch type.
//!
//! Processors run in registration order. Returning `Ok(true)` stops the current list,
//! `Ok(false)` continues to the next processor, and an error stops the list and propagates
//! to the caller. Different events may be handled concurrently in separate tasks, so
//! implementations must synchronize mutable state themselves.

use std::{fmt::Debug, sync::Arc};

use crate::{
    bot_context::BotContext,
    event::{self, Post},
};
use async_trait::async_trait;

/// Unified dispatch type stored in a processor list.
///
/// Each variant wraps one processor trait object. Types generated by `#[processor]` and
/// module instances are converted into this type through `Into<Processor>` and registered
/// with [`crate::bot_context::BotContextBuilder`] or
/// [`crate::bot_context::BotServerBuilder`].
#[derive(Debug)]
pub enum Processor {
    /// Handles every [`event::Post`], including meta events, notices, requests, and messages.
    Post(Box<dyn PostProcessor>),
    /// Handles only [`event::Post::Message`]; `message_sent` events are not dispatched here.
    Message(Box<dyn MessageProcessor>),
    /// Handles only [`event::Post::Notice`].
    Notice(Box<dyn NoticeProcessor>),
    /// Handles only [`event::Post::Request`].
    Request(Box<dyn RequestProcessor>),
    /// A module that can nest other processors, handles every event, and can appear as a
    /// menu entry.
    Module(Box<dyn ModuleProcessor>),
}

impl Processor {
    /// Returns the stable identifier of the processor.
    ///
    /// Macro-generated identifiers usually contain the crate name, module path, and
    /// function name, which helps locate logs. Custom implementations should make the
    /// value readable and stable within a list; this method does not check uniqueness.
    pub fn id(&self) -> &'static str {
        match self {
            Processor::Post(processor) => processor.id(),
            Processor::Message(processor) => processor.id(),
            Processor::Notice(processor) => processor.id(),
            Processor::Request(processor) => processor.id(),
            Processor::Module(processor) => processor.id(),
        }
    }

    /// Dispatches an event to the handler selected by this variant and the event type.
    ///
    /// The `Message`, `Notice`, and `Request` variants only handle matching event types and
    /// return `Ok(false)` for other events so the caller can continue with the remaining
    /// processors. The `Post` and `Module` variants receive every event. Returning
    /// `Ok(true)` means the processor claimed the event and the caller should stop
    /// dispatching the current list; `Ok(false)` means continue. Errors are propagated from
    /// the processor unchanged.
    pub async fn process(
        &self,
        bot_ctx: Arc<BotContext>,
        post: &event::Post,
    ) -> anyhow::Result<bool> {
        if let (Processor::Message(processor), event::Post::Message(message)) = (self, post) {
            processor.process_message(bot_ctx, message).await
        } else if let (Processor::Notice(processor), event::Post::Notice(notice)) = (self, post) {
            processor.process_notice(bot_ctx, notice).await
        } else if let (Processor::Request(processor), event::Post::Request(request)) = (self, post)
        {
            processor.process_request(bot_ctx, request).await
        } else if let Processor::Post(processor) = self {
            processor.process_post(bot_ctx, post).await
        } else if let Processor::Module(processor) = self {
            processor.process_post(bot_ctx, post).await
        } else {
            Ok(false)
        }
    }
}

/// Processor for every event type.
///
/// Usually generated for an asynchronous function whose second parameter is `&Post`, through
/// `#[processor]`. A processor may be called concurrently by tasks handling different
/// events; implementations must synchronize mutable state and must not rely on a global
/// cross-event call order.
#[async_trait]
pub trait PostProcessor: Send + Sync + Debug {
    /// Returns the stable identifier used in logs and diagnostics.
    fn id(&self) -> &'static str;

    /// Handles an event and decides whether to continue the current processor list.
    ///
    /// Returning `Ok(true)` means the event was handled and subsequent processors are
    /// skipped; `Ok(false)` means continue. Returning an error stops the current list and
    /// propagates the error, but does not close the connection or terminate the bot.
    async fn process_post(
        &self,
        bot_ctx: Arc<BotContext>,
        post: &event::Post,
    ) -> anyhow::Result<bool>;
}

/// Processor for chat message events.
///
/// Dispatched for [`event::Post::Message`]. The `message_sent` event is represented by
/// [`event::Post::MessageSent`] and does not call this trait.
#[async_trait]
pub trait MessageProcessor: Send + Sync + Debug {
    /// Returns the stable identifier used in logs and diagnostics.
    fn id(&self) -> &'static str;

    /// Handles a message and decides whether to continue the current processor list.
    ///
    /// Returning `Ok(true)` means the message was handled and subsequent processors are
    /// skipped; `Ok(false)` means continue. Returning an error stops the current list and
    /// propagates the error. Different messages may be handled concurrently in separate
    /// tasks, so implementations must synchronize mutable state themselves.
    async fn process_message(
        &self,
        bot_ctx: Arc<BotContext>,
        message: &event::Message,
    ) -> anyhow::Result<bool>;
}

/// Processor for notice events.
///
/// Notices include group file uploads, administrator changes, member joins and leaves,
/// mutes, recalls, pokes, and similar events. Unknown notice types are passed as
/// [`event::Notice::Unknown`].
#[async_trait]
pub trait NoticeProcessor: Send + Sync + Debug {
    /// Returns the stable identifier used in logs and diagnostics.
    fn id(&self) -> &'static str;

    /// Handles a notice and decides whether to continue the current processor list.
    ///
    /// Returning `Ok(true)` means the notice was handled and subsequent processors are
    /// skipped; `Ok(false)` means continue. Returning an error stops the current list and
    /// propagates the error.
    async fn process_notice(
        &self,
        bot_ctx: Arc<BotContext>,
        event: &event::Notice,
    ) -> anyhow::Result<bool>;
}

/// Processor for request events.
///
/// Requests include friend requests and group requests. Unknown request types are passed as
/// [`event::Request::Unknown`].
#[async_trait]
pub trait RequestProcessor: Send + Sync + Debug {
    /// Returns the stable identifier used in logs and diagnostics.
    fn id(&self) -> &'static str;

    /// Handles a request and decides whether to continue the current processor list.
    ///
    /// Returning `Ok(true)` means the request was handled and subsequent processors are
    /// skipped; `Ok(false)` means continue. Returning an error stops the current list and
    /// propagates the error. The framework does not automatically approve or reject the
    /// request.
    async fn process_request(
        &self,
        bot_ctx: Arc<BotContext>,
        request: &event::Request,
    ) -> anyhow::Result<bool>;
}

/// Module that can nest processors and expose menu metadata.
///
/// Usually generated by applying `#[module]` to `impl Module for ...`. A module is itself a
/// processor and receives every event; its implementation decides how to organize the child
/// processors returned by [`Self::processors`]. Modules may nest, but the library does not
/// detect reference cycles.
#[async_trait]
pub trait ModuleProcessor: Send + Sync + Debug {
    /// Returns the stable identifier used in logs and diagnostics.
    fn id(&self) -> &'static str;

    /// Returns the module name shown to users.
    fn name(&self) -> &'static str;

    /// Returns the help text shown to users.
    fn help(&self) -> &'static str;

    /// Handles an event and decides whether to continue the current processor list.
    ///
    /// Returning `Ok(true)` means the event was handled and subsequent processors are
    /// skipped; `Ok(false)` means continue. Returning an error stops the current list and
    /// propagates the error.
    async fn process_post(
        &self,
        bot_ctx: Arc<BotContext>,
        post: &event::Post,
    ) -> anyhow::Result<bool>;

    /// Returns the processors contained in this module.
    ///
    /// The list is shared through an `Arc`; callers can read it but cannot modify it through
    /// this reference. The module's own handling logic typically invokes these child
    /// processors in order.
    fn processors(&self) -> Arc<Vec<Processor>>;
}

/// Generic [`ModuleProcessor`] implementation constructed by the `#[module]` macro.
///
/// This type stores module metadata and child processors together and forwards events to
/// the child processor list. All fields are static strings or a shared processor list, and
/// no mutation API is provided after construction.
#[derive(Debug)]
pub struct ProcessModule {
    /// Stable module identifier, usually composed of the crate name, module path, and
    /// struct name.
    pub id: &'static str,
    /// Module name shown in menus.
    pub name: &'static str,
    /// Help text shown in menus.
    pub help: &'static str,
    /// Processors contained in the module, dispatched in registration order.
    pub processors: Arc<Vec<Processor>>,
}

#[async_trait]
impl ModuleProcessor for ProcessModule {
    fn id(&self) -> &'static str {
        self.id
    }
    fn name(&self) -> &'static str {
        self.name
    }
    fn help(&self) -> &'static str {
        self.help
    }
    async fn process_post(
        &self,
        bot_ctx: Arc<BotContext>,
        post: &event::Post,
    ) -> anyhow::Result<bool> {
        loop_processors(bot_ctx, self.processors.iter(), post).await
    }
    fn processors(&self) -> Arc<Vec<Processor>> {
        self.processors.clone()
    }
}

impl Into<Processor> for Box<dyn PostProcessor> {
    fn into(self) -> Processor {
        Processor::Post(self)
    }
}

impl Into<Processor> for Box<dyn MessageProcessor> {
    fn into(self) -> Processor {
        Processor::Message(self)
    }
}

impl Into<Processor> for Box<dyn NoticeProcessor> {
    fn into(self) -> Processor {
        Processor::Notice(self)
    }
}

impl Into<Processor> for Box<dyn RequestProcessor> {
    fn into(self) -> Processor {
        Processor::Request(self)
    }
}

impl Into<Processor> for Box<dyn ModuleProcessor> {
    fn into(self) -> Processor {
        Processor::Module(self)
    }
}

pub(crate) async fn loop_processors(
    bot_ctx: Arc<BotContext>,
    processor_iter: core::slice::Iter<'_, Processor>,
    post: &Post,
) -> anyhow::Result<bool> {
    for processor in processor_iter {
        let processe_result = processor.process(bot_ctx.clone(), post).await;
        match processe_result {
            Ok(b) => {
                if b {
                    tracing::debug!(
                        "post processed, id : {:?} , post : {:?}",
                        processor.id(),
                        post
                    );
                    return Ok(b);
                }
            }
            Err(err) => {
                tracing::error!(
                    "processor error, id: {:?} , post {:?} error: {:?}",
                    processor.id(),
                    post,
                    err
                );
                return Err(err);
            }
        }
    }
    Ok(false)
}
